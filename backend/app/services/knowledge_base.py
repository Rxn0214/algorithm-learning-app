def find_knowledge_answer(question: str) -> str:
    """从知识库中查找匹配的答案（离线回退用）"""
    if not question:
        return ""
    for keyword, answer in KNOWLEDGE_BASE.items():
        if keyword in question:
            return answer
    return ""


def get_lesson_context(lesson_id: int) -> str:
    """获取课时知识上下文"""
    return LESSON_KNOWLEDGE.get(lesson_id, "")
