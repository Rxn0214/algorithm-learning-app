const GUIDER_PREFIX = '😊 同学你好～'
const TUTOR_PREFIX = '让我来帮你分析一下 🤔'

/**
 * 根据问题查找知识库答案
 * @param {string} question - 用户的问题
 * @param {number|null} lessonId - 当前课时ID
 * @returns {string|null} 匹配的答案，null表示无匹配
 */
export function findAnswer(question, lessonId = null) {
  const q = question.toLowerCase()

  // 优先匹配课时相关
  const lessonContexts = {
    1: '你问的是课时1（算法的概念）的内容。',
    2: '这个问题涉及课时2（算法的特征）。',
    3: '这属于课时3（算法的描述）的知识点。',
    4: '这属于课时4（流程图基础）的内容。',
    5: '这是课时5（顺序结构）的内容。',
    6: '这是课时6（分支结构）的知识点。',
    7: '这属于课时7（循环结构）的内容。',
    8: '这属于课时8（程序实现）的内容。'
  }

  // 检查是否有关键词匹配
  for (const entry of KNOWLEDGE) {
    if (entry.answer === null) continue

    // 如果有 checkAll，要求所有关键词都匹配
    if (entry.checkAll) {
      const allMatch = entry.checkAll.every(kw => q.includes(kw))
      if (!allMatch) continue
    }

    // 检查关键词匹配
    const match = entry.keywords.some(kw => q.includes(kw))
    if (match) {
      const context = lessonId ? `（关于${lessonContexts[lessonId] || ''}）` : ''
      return entry.answer + '\n\n' + context
    }
  }

  return null
}

/**
 * 生成本地回复
 * @param {string} question - 用户问题
 * @param {string} agentType - agent类型（guider/tutor）
 * @param {number|null} lessonId - 当前课时ID
 * @returns {string} 回复内容
 */
export function generateLocalReply(question, agentType = 'tutor', lessonId = null) {
  // 先尝试知识库匹配
  const answer = findAnswer(question, lessonId)
  if (answer) {
    if (agentType === 'guider') {
      return `${GUIDER_PREFIX} ${answer}`
    } else {
      return `${TUTOR_PREFIX}\n\n${answer}`
    }
  }

  // 无匹配时的友好回复
  const fallbacks = {
    guider: [
      `好问题！关于「${question}」我建议你先回顾一下对应课时的知识点，理解基础概念后再深入。需要我帮你看看是哪个课时的内容吗？`,
      `这个问题挺有意思的！在学习「算法与程序实现」时，建议你先浏览一遍课时列表，找到对应的章节。如果你告诉我具体是哪个知识点，我可以给你详细讲解哦～`,
      `关于「${question}」的建议学习路径：① 先通读课本对应章节 ② 再看课时里的知识点 ③ 做练习题巩固 ④ 有疑问随时回来问我！`
    ],
    tutor: [
      `关于「${question}」，我们从基础概念开始分析。首先你要理解这个知识点属于三大基本结构（顺序、分支、循环）中的哪一类，然后结合具体例子来掌握它。你能告诉我你学到哪个课时了吗？`,
      `让我来分析「${question}」这个问题。我们可以分三步：① 明确问题的输入和输出 ② 设计解决步骤 ③ 用流程图或伪代码表达。你目前卡在哪一步呢？`,
      `这个问题涉及的知识点，建议你结合课本和课时内容来理解。如果能把具体题目发给我，我可以带你一步步分析解题思路！`
    ]
  }

  const list = fallbacks[agentType] || fallbacks.tutor
  return list[question.length % list.length]
}
